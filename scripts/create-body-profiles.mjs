import fs from 'node:fs';
const roster=JSON.parse(fs.readFileSync('art/roster-physics.json','utf8'));
const names=['MATUS','MAGIC','BAMBI','TORRES','CHOMPA','MEAT'];
export const bodyProfiles=roster.players.map((p,i)=>{
  if(p.name!==names[i])throw Error('Physical roster order mismatch');
  if(p.height_cm!==null && (p.height_cm<130 || p.height_cm>230))throw Error('Height outside supported range');
  const mass={lean:1,average:2,broad:3,stocky:3,heavy:4}[p.build]??2;
  const height=p.height_cm===null?40:Math.max(36,Math.min(44,Math.round(p.height_cm*40/180)));
  return {name:p.name,height_px:height,radius:mass===4?8:mass===3?7:mass===1?5:6,mass,
    height_cm:p.height_cm??0,weight_kg:p.weight_kg??0,confirmed:p.height_cm!==null && p.build!==null};
});
const rows=bodyProfiles.map(p=>`    {${p.height_px},${p.radius},${p.mass},${p.height_cm},${p.weight_kg}} /* ${p.name}${p.confirmed?'':' - neutral pending measurements'} */`).join(',\n');
fs.writeFileSync('game/plugins/basketball/engine/include/jam_bodies.h',`/* Generated by scripts/create-body-profiles.mjs; see art/roster-physics.json. */\n#ifndef JAM_BODIES_H\n#define JAM_BODIES_H\ntypedef struct {uint8_t height_px,radius,mass;uint16_t height_cm,weight_kg;} jam_body_t;\nstatic const jam_body_t jam_bodies[6]={\n${rows}\n};\n#endif\n`);
console.log('Generated six physical profiles from confirmed heights/builds; unknown weights stay zero.');
