const frequency=note=>Math.max(0,Math.min(2047,Math.round(2048-131072/(440*2**((note-69)/12)))));
const encode=steps=>{
 const bytes=[];
 for(const s of steps)for(let ticks=s.ticks;ticks>0;ticks-=16){
  const duration=Math.min(ticks,16),f=s.note?frequency(s.note):0;
  // Two channels: pulse 1 (all five registers) and noise (four registers).
  bytes.push(((duration-1)<<4)|2,0xF8,0,s.duty<<6,(s.note?s.volume:0)<<4,f&255,0x80|(f>>8),
   0x7B,0,s.noiseVolume<<4,s.noise,0x80);
 }
 // Silence both DACs before the native terminator, including preempted tails.
 bytes.push(3,0x20,0,0x23,0,7);
 return bytes;
};
let source='/* Generated by scripts/create-sfx.mjs; editable PSG recipes live there. */\n';
for(const [name,,steps] of effects)source+=`static const uint8_t jam_sample_${name.toLowerCase()}[]={${encode(steps)}};\n`;
source+=`static const uint8_t * const jam_sfx_samples[]={${effects.map(([n])=>`jam_sample_${n.toLowerCase()}`).join(',')}};\n`;
source+=`static const uint8_t jam_sfx_priority[]={${effects.map(([,p])=>p)}};\n`;
fs.writeFileSync('game/plugins/basketball/engine/include/jam_sfx_data.h',source);
fs.mkdirSync('art/audio',{recursive:true});
fs.writeFileSync('art/audio/sfx.json',JSON.stringify({driver:'GB Studio native SFX, 256 Hz, pulse 1 + noise 4',effects:effects.map(([name,priority,steps])=>({name,priority,durationMs:steps.reduce((n,s)=>n+s.ticks,0)*1000/256,steps,bytes:encode(steps)}))},null,2)+'\n');
