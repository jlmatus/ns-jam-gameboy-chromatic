import fs from 'node:fs';
// Five 8x8 native tiles: outlined empty cell and four fill amounts.
const tiles=[];
for(const fill of [0,2,3,5,6])for(let y=0;y<8;y++){
  let bits=0;
  if(y===1||y===6)bits=255;
  else if(y>1&&y<6){bits=129;for(let x=1;x<=fill;x++)bits|=1<<(7-x);}
  tiles.push(bits,bits);
}
const opaque=tiles.map((v,i)=>i%2===0?255:v);
fs.writeFileSync('game/plugins/basketball/engine/include/jam_turbo_hud.h',
  `/* Generated by scripts/create-turbo-hud.mjs; tiles 232..236 stay resident. */\n`+
  `static const unsigned char jam_turbo_tiles[]={${tiles.join(',')}};\n`+
  `static const unsigned char jam_turbo_opaque_tiles[]={${opaque.join(',')}};\n`);
console.log('Authored five normal/opaque turbo gauge tiles.');
